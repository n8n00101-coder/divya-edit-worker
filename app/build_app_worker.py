#!/usr/bin/env python3
"""Bundle built/divya-app/* into a single static Worker (divya-app) and deploy it.
Run with shell credentials provider cloudflare-divya:  python3 build_app_worker.py [--deploy]"""
import base64, json, os, subprocess, sys
D = os.path.join(os.path.dirname(os.path.abspath(__file__)), "divya-app")
TYPES = {".html": "text/html; charset=utf-8", ".css": "text/css; charset=utf-8", ".js": "application/javascript; charset=utf-8", ".png": "image/png", ".webmanifest": "application/manifest+json"}
files = {}
for f in sorted(os.listdir(D)):
    ext = os.path.splitext(f)[1]
    if ext not in TYPES: continue
    b = open(os.path.join(D, f), "rb").read()
    files["/" + f] = {"t": TYPES[ext], "b": base64.b64encode(b).decode()}
files["/"] = files["/index.html"]
js = """// Divya app (PWA) static host. Generated by built/build_app_worker.py, do not edit by hand.
const F = %s;
const cache = {};
function bytes(p){ if(!cache[p]){ const s=atob(F[p].b); const u=new Uint8Array(s.length); for(let i=0;i<s.length;i++)u[i]=s.charCodeAt(i); cache[p]=u; } return cache[p]; }
export default { async fetch(req){
  const url = new URL(req.url); let p = url.pathname;
  if(!F[p]) p = p.includes(".") ? null : "/";
  if(!p) return new Response("Not found", {status:404});
  const h = {"content-type":F[p].t, "x-content-type-options":"nosniff", "referrer-policy":"strict-origin-when-cross-origin",
    "permissions-policy":"microphone=(self), camera=()",
    "cache-control": (p==="/sw.js"||p==="/"||p.endsWith(".html")||p.endsWith(".webmanifest")) ? "no-cache" : "public, max-age=3600"};
  if(p==="/sw.js") h["service-worker-allowed"]="/";
  return new Response(bytes(p), {headers:h});
}};
""" % json.dumps(files)
out = os.path.join(os.path.dirname(D), "divya-app-worker.js")
open(out, "w").write(js)
print("bundle", out, len(js))
if "--deploy" in sys.argv:
    A = "ba39b7fb8bae4e32999a8a77c8e04039"
    r = subprocess.run(["curl", "-s", "-X", "PUT", f"https://api.cloudflare.com/client/v4/accounts/{A}/workers/scripts/divya-app",
        "-F", 'metadata={"main_module":"worker.js","compatibility_date":"2024-11-01"};type=application/json',
        "-F", f"worker.js=@{out};filename=worker.js;type=application/javascript+module"], capture_output=True, text=True)
    j = json.loads(r.stdout); print("deploy", j["success"], j.get("errors"))
    r = subprocess.run(["curl", "-s", "-X", "POST", f"https://api.cloudflare.com/client/v4/accounts/{A}/workers/scripts/divya-app/subdomain",
        "-H", "content-type: application/json", "-d", '{"enabled":true,"previews_enabled":false}'], capture_output=True, text=True)
    print("subdomain", r.stdout[:160].replace("\n", " "))
